export default function PortfolioPage() {
  const params = useParams();
  const username = params.username as string;
  const [portfolio, setPortfolio] = useState<Portfolio | null>(null);
  const [loading, setLoading] = useState(true);
  const [notFound, setNotFound] = useState(false);

  useEffect(() => {
    if (!username) return;
    fetch(`${API}/api/portfolio/public/${username}`)
      .then((res) => { if (res.status === 404) { setNotFound(true); return null; } return res.json(); })
      .then((data) => { if (data) setPortfolio(data); })
      .catch(() => setNotFound(true))
      .finally(() => setLoading(false));
  }, [username]);

  if (loading) {
    return (
      <div className="min-h-screen bg-[#0a0a0a] flex items-center justify-center">
        <div className="flex flex-col items-center gap-4">
          <div className="w-10 h-10 border-2 border-violet-500 border-t-transparent rounded-full animate-spin" />
          <p className="text-gray-500 text-sm">Loading portfolio…</p>
        </div>
      </div>
    );
  }

  if (notFound || !portfolio) {
    return (
      <div className="min-h-screen bg-[#0a0a0a] flex items-center justify-center text-center px-4">
        <div>
          <p className="text-7xl mb-6">🔍</p>
          <h1 className="text-3xl font-bold text-white mb-3">Portfolio not found</h1>
          <p className="text-gray-500">@{username} hasn't built their portfolio yet.</p>
        </div>
      </div>
    );
  }

  const data = portfolio.portfolio_data;
  const config = data.design_config;
  const hue = data.accent_hue ?? 210;
  // If Gemini generated custom HTML, render that instead of the preset themes.
  if (data.html) {
    return <CustomHTMLPortfolio html={data.html} />;
  }

  // Use dynamic renderer if design_config exists, otherwise fallback to theme
  if (config && config.color_mood === "vibrant") {
    return <CreativeTheme portfolio={portfolio} data={data} />;
  }

  const theme = portfolio.theme || "minimal";
  return (
    <>
      {data.design_emoji && <CursorEmoji emoji={data.design_emoji} size={config && config.color_mood === "vibrant" ? "8rem" : "2rem"} />}
      {data.interactive_bg && <InteractiveBg hue={hue} />}
      {theme === "dark" && <DarkTheme portfolio={portfolio} data={data} />}
      {theme === "creative" && <CreativeTheme portfolio={portfolio} data={data} />}
      {theme === "minimal" && <MinimalTheme portfolio={portfolio} data={data} />}
    </>
  );
}

