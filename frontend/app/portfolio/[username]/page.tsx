// Cursor-following emoji component with head tilt
function CursorEmoji({ emoji, size = "2rem" }: { emoji: string; size?: string }) {
  const ref = useRef<HTMLDivElement>(null);
  const pos = useRef({ x: -200, y: -200 });
  const centerRef = useRef({ x: 0, y: 0 });

  useEffect(() => {
    centerRef.current = { x: window.innerWidth / 2, y: window.innerHeight / 2 };
    const move = (e: MouseEvent) => {
      pos.current = { x: e.clientX, y: e.clientY };
      // Calculate head tilt angle toward cursor
      if (ref.current) {
        const dx = e.clientX - centerRef.current.x;
        const dy = e.clientY - centerRef.current.y;
        const angle = Math.atan2(dy, dx) * (180 / Math.PI);
        ref.current.style.transform = `translate(${e.clientX - 40}px, ${e.clientY - 40}px) rotate(${angle * 0.3}deg)`;
      }
    };
    window.addEventListener("mousemove", move);
    return () => { window.removeEventListener("mousemove", move); };
  }, []);

  return (
    <div ref={ref} className="fixed top-0 left-0 z-50 pointer-events-none select-none"
      style={{ fontSize: size, transition: "transform 0.1s ease-out", willChange: "transform" }}>
      {emoji}
    </div>
  );
}

// Interactive animated background with gradient support
function InteractiveBg({ hue, gradient }: { hue: number; gradient?: { from: string; to: string } }) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const mouse = useRef({ x: 0, y: 0 });

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext("2d")!;
    let w = canvas.width = window.innerWidth;
    let h = canvas.height = window.innerHeight;
    const onResize = () => { w = canvas.width = window.innerWidth; h = canvas.height = window.innerHeight; };
    window.addEventListener("resize", onResize);
    window.addEventListener("mousemove", (e) => { mouse.current = { x: e.clientX, y: e.clientY }; });

    // Floating dots
    const dots = Array.from({ length: 55 }, () => ({
      x: Math.random() * window.innerWidth,
      y: Math.random() * window.innerHeight,
      r: Math.random() * 2.5 + 1,
      vx: (Math.random() - 0.5) * 0.4,
      vy: (Math.random() - 0.5) * 0.4,
      opacity: Math.random() * 0.4 + 0.1,
    }));

    let frame = 0;
    const draw = () => {
      // Draw gradient background if specified
      if (gradient) {
        const g = ctx.createLinearGradient(0, 0, w, h);
        g.addColorStop(0, gradient.from);
        g.addColorStop(1, gradient.to);
        ctx.fillStyle = g;
        ctx.fillRect(0, 0, w, h);
      } else {
        ctx.clearRect(0, 0, w, h);
      }

      // Mouse glow
      const glowGrad = ctx.createRadialGradient(mouse.current.x, mouse.current.y, 0, mouse.current.x, mouse.current.y, 280);
      glowGrad.addColorStop(0, `hsla(${hue},80%,65%,0.12)`);
      glowGrad.addColorStop(1, `hsla(${hue},80%,65%,0)`);
      ctx.fillStyle = glowGrad;
      ctx.fillRect(0, 0, w, h);

      dots.forEach(d => {
        d.x += d.vx; d.y += d.vy;
        if (d.x < 0 || d.x > w) d.vx *= -1;
        if (d.y < 0 || d.y > h) d.vy *= -1;
        dots.forEach(d2 => {
          const dx = d.x - d2.x, dy = d.y - d2.y;
          const dist = Math.sqrt(dx*dx + dy*dy);
          if (dist < 110) {
            ctx.beginPath();
            ctx.moveTo(d.x, d.y);
            ctx.lineTo(d2.x, d2.y);
            ctx.strokeStyle = `hsla(${hue},60%,70%,${0.12 * (1 - dist/110)})`;
            ctx.lineWidth = 0.8;
            ctx.stroke();
          }
        });
        ctx.beginPath();
        ctx.arc(d.x, d.y, d.r, 0, Math.PI * 2);
        ctx.fillStyle = `hsla(${hue},70%,70%,${d.opacity})`;
        ctx.fill();
      });
      frame = requestAnimationFrame(draw);
    };
    draw();
    return () => { cancelAnimationFrame(frame); window.removeEventListener("resize", onResize); };
  }, [hue, gradient]);

  return <canvas ref={canvasRef} className="fixed inset-0 pointer-events-none z-0" />;
}

